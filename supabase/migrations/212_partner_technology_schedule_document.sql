-- Permit controlled Technology Schedule templates in the partner document portal.
DO $$ DECLARE c RECORD;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = 'public.partner_generated_documents'::regclass
      AND contype = 'c'
      AND pg_get_constraintdef(oid) LIKE '%''MASTER_PARTNER_AGREEMENT''%'
  LOOP
    EXECUTE format('ALTER TABLE public.partner_generated_documents DROP CONSTRAINT %I', c.conname);
  END LOOP;
END $$;

ALTER TABLE public.partner_generated_documents ADD CONSTRAINT partner_generated_documents_document_type_check CHECK (document_type IN (
  'MASTER_PARTNER_AGREEMENT','ACTIVATION_CONFIRMATION','CUSTOMER_ASSIGNMENT','IMPLEMENTATION_WORK_ORDER',
  'CHANGE_ORDER','DATA_PROCESSING_ADDENDUM','TECHNOLOGY_SCHEDULE','TRAINING_RECORD','UAT_RECORD',
  'COMPLETION_HANDOVER_RECORD','GO_LIVE_DECISION','COMMISSION_STATEMENT','IMPLEMENTATION_FEE_STATEMENT',
  'PAYOUT_STATEMENT','GRADE_CONFIRMATION','FORMAL_NOTICE','REFERRAL_PARTNER_AGREEMENT',
  'REFERRAL_COMMISSION_SCHEDULE','REFERRAL_ACCEPTANCE_NOTICE','INFORMATION_REQUEST_NOTICE',
  'DUPLICATE_NOTICE','REJECTION_NOTICE','LOST_OR_EXPIRED_NOTICE','SUSPENSION_OR_TERMINATION_NOTICE',
  'REFERRAL_COMMISSION_STATEMENT'
));

NOTIFY pgrst,'reload schema';
